Ideal::Ideal(RingPtr R, std::vector<Poly> gens) : R_(std::move(R)) {
  for (auto& g : gens) {
    if (g.ring().get() != R_.get()) throw std::invalid_argument("helmer: generator in wrong ring");
    if (!g.is_zero()) gens_.push_back(std::move(g));
  }
}

Ideal Ideal::parse(RingPtr R, const std::vector<std::string>& gens) {
  std::vector<Poly> G;
  for (auto& s : gens) G.emplace_back(R, s);
  return Ideal(std::move(R), std::move(G));
}

const GB& Ideal::gb() const {
  if (!gb_) gb_ = std::make_shared<GB>(groebner_drl(R_, gens_));
  return *gb_;
}

Ideal& Ideal::canonicalise() {
  gens_ = gb().polys;
  return *this;
}

bool Ideal::is_unit() const { return gb().is_unit(); }
bool Ideal::is_zero() const { return gens_.empty(); }

// Maximum independent set for the monomial ideal generated by `leads`:
// largest U ⊆ vars with no lead monomial supported inside U.
std::vector<int> max_independent_set(int n, const std::vector<std::vector<int>>& leads) {
  // supports as sorted variable lists, minimalised
  std::vector<std::vector<int>> sup;
  for (auto& l : leads) {
    std::vector<int> s;
    for (int i = 0; i < n; ++i)
      if (l[i] > 0) s.push_back(i);
    sup.push_back(std::move(s));
  }
  std::sort(sup.begin(), sup.end(), [](auto& a, auto& b) { return a.size() < b.size(); });
  std::vector<std::vector<int>> mins;
  for (auto& s : sup) {
    bool redundant = false;
    for (auto& m : mins)
      if (std::includes(s.begin(), s.end(), m.begin(), m.end())) { redundant = true; break; }
    if (!redundant) mins.push_back(s);
  }
  // Minimum hitting set H by branch and bound; U = complement.
  std::vector<char> inH(n, 0), best(n, 1);
  int bestsize = n + 1;
  std::function<void(int)> rec = [&](int size) {
    if (size >= bestsize) return;
    const std::vector<int>* pick = nullptr;
    for (auto& m : mins) {
      bool hit = false;
      for (int v : m)
        if (inH[v]) { hit = true; break; }
      if (!hit && (!pick || m.size() < pick->size())) pick = &m;
    }
    if (!pick) {
      bestsize = size;
      best = inH;
      return;
    }
    for (int v : *pick) {
      inH[v] = 1;
      rec(size + 1);
      inH[v] = 0;
    }
  };
  rec(0);
  std::vector<int> U;
  for (int i = 0; i < n; ++i)
    if (!best[i]) U.push_back(i);
  return U;
}

std::vector<int> Ideal::independent_set() const {
  if (is_unit()) return {};
  return max_independent_set(R_->nvars(), gb().lead);
}

int Ideal::dim() const {
  if (is_unit()) return -1;
  return static_cast<int>(independent_set().size());
}

int Ideal::codim() const {
  if (is_unit()) return R_->nvars() + 1;
  return R_->nvars() - dim();
}

Poly Ideal::normal_form(const Poly& f) const {
  const GB& G = gb();
  if (G.polys.empty()) return f;
  if (G.is_unit()) return Poly(R_);
  const slong k = static_cast<slong>(G.polys.size());
  std::vector<fmpq_mpoly_struct*> B;
  std::vector<Poly> Qs;
  Qs.reserve(k);
  std::vector<fmpq_mpoly_struct*> Qp;
  for (auto& g : G.polys) B.push_back(const_cast<fmpq_mpoly_struct*>(g.raw()));
  for (slong i = 0; i < k; ++i) {
    Qs.emplace_back(R_);
    Qp.push_back(Qs.back().raw());
  }
  Poly r(R_);
  fmpq_mpoly_divrem_ideal(Qp.data(), r.raw(), f.raw(), B.data(), k, R_->ctx());
  return r;
}

bool Ideal::contains(const Poly& f) const { return normal_form(f).is_zero(); }

bool Ideal::contains(const Ideal& J) const {
  for (auto& g : J.gens())
    if (!contains(g)) return false;
  return true;
}

bool Ideal::equals(const Ideal& J) const {
  const GB& A = gb();
  const GB& B = J.gb();
  if (A.polys.size() != B.polys.size()) return false;
  // reduced monic GBs are unique; compare as sets
  std::vector<bool> used(B.polys.size(), false);
  for (auto& a : A.polys) {
    bool found = false;
    for (size_t j = 0; j < B.polys.size(); ++j)
      if (!used[j] && a.equal(B.polys[j])) { used[j] = found = true; break; }
    if (!found) return false;
  }
  return true;
}

bool Ideal::is_homogeneous() const {
  for (auto& g : gens_) {
    long d = g.total_degree();
    for (long i = 0; i < g.nterms(); ++i) {
      auto e = g.term_exp(i);
      long s = 0;
      for (long x : e) s += x;
      if (s != d) return false;
    }
  }
  return true;
}

std::string Ideal::str() const {
  std::ostringstream o;
  o << "ideal(";
  for (size_t i = 0; i < gens_.size(); ++i) o << (i ? ", " : "") << gens_[i].str();
  o << ")";
  return o.str();
}

std::string Ideal::key() const {
  std::vector<std::string> s;
  for (auto& g : gb().polys) s.push_back(g.str());
  std::sort(s.begin(), s.end());
  std::string k;
  for (auto& x : s) k += x + ";";
  return k;
}

Ideal operator+(const Ideal& I, const Ideal& J) {
  std::vector<Poly> g = I.gens();
  g.insert(g.end(), J.gens().begin(), J.gens().end());
  return Ideal(I.ring(), std::move(g));
}
Ideal operator+(const Ideal& I, const Poly& f) {
  std::vector<Poly> g = I.gens();
  g.push_back(f);
  return Ideal(I.ring(), std::move(g));
}

Ideal eliminate(const Ideal& I, const std::vector<int>& elim) {
  const RingPtr& R = I.ring();
  const int n = R->nvars();
  std::vector<char> is_e(n, 0);
  for (int v : elim) is_e[v] = 1;
  std::vector<int> perm;
  for (int v = 0; v < n; ++v)
    if (is_e[v]) perm.push_back(v);
  const int ebl = static_cast<int>(perm.size());
  for (int v = 0; v < n; ++v)
    if (!is_e[v]) perm.push_back(v);
  if (ebl == 0) return I;
  if (ebl == n) {  // eliminating everything: result is 0 or 1
    return I.is_unit() ? Ideal(R, {Poly::constant(R, 1)}) : Ideal(R);
  }
  GB G = groebner(R, I.gens(), perm, ebl);
  std::vector<Poly> out;
  for (auto& g : G.polys) {
    bool free = true;
    for (int v : elim)
      if (g.involves(v)) { free = false; break; }
    if (free) out.push_back(g);
  }
  return Ideal(R, std::move(out));
}

Ideal embed(const Ideal& I, const RingPtr& S, const std::vector<int>& map) {
  std::vector<Poly> g;
  for (auto& f : I.gens()) g.push_back(f.embed(S, map));
  return Ideal(S, std::move(g));
}

Ideal restrict_to(const Ideal& I, const RingPtr& R, const std::vector<int>& map) {
  // map[i] = index in I.ring() of variable i of R; generators must avoid other vars.
  const RingPtr& S = I.ring();
  std::vector<int> back(S->nvars(), -1);
  for (int i = 0; i < R->nvars(); ++i) back[map[i]] = i;
  std::vector<Poly> vals;
  for (int j = 0; j < S->nvars(); ++j)
    vals.push_back(back[j] >= 0 ? Poly::var(R, back[j]) : Poly(R));
  std::vector<Poly> g;
  for (auto& f : I.gens()) {
    for (int j = 0; j < S->nvars(); ++j)
      if (back[j] < 0 && f.involves(j))
        throw std::logic_error("helmer: restrict_to: generator involves a dropped variable");
    g.push_back(f.substitute(R, vals));
  }
  return Ideal(R, std::move(g));
}

namespace {
// R with one extra variable appended (name chosen to avoid clashes).
RingPtr ring_plus_one(const RingPtr& R, const std::string& base, int& idx) {
  std::vector<std::string> names = R->names();
  std::string nm = base;
  while (R->index_of(nm) >= 0) nm += "_";
  names.push_back(nm);
  idx = static_cast<int>(names.size()) - 1;
  return Ring::make(std::move(names));
}
std::vector<int> identity_map(int n) {
  std::vector<int> m(n);
  for (int i = 0; i < n; ++i) m[i] = i;
  return m;
}
}  // namespace

Ideal saturate(const Ideal& I, const Poly& f) {
  const RingPtr& R = I.ring();
  if (f.is_zero()) return Ideal(R, {Poly::constant(R, 1)});
  if (f.is_constant()) return I;
  int t;
  RingPtr S = ring_plus_one(R, "helmer_t", t);
  auto m = identity_map(R->nvars());
  std::vector<Poly> g;
  for (auto& p : I.gens()) g.push_back(p.embed(S, m));
  // Localising at f or its squarefree part gives the same saturation.
  g.push_back(Poly::var(S, t) * radical_part(f).embed(S, m) - Poly::constant(S, 1));
  std::vector<int> perm{t};
  for (int i = 0; i < R->nvars(); ++i) perm.push_back(i);
  GB G = groebner(S, g, perm, 1);
  std::vector<Poly> out;
  std::vector<Poly> vals;
  for (int i = 0; i < R->nvars(); ++i) vals.push_back(Poly::var(R, i));
  vals.push_back(Poly(R));
  for (auto& p : G.polys)
    if (!p.involves(t)) out.push_back(p.substitute(R, vals));
  return Ideal(R, std::move(out));
}

Poly random_combination(const std::vector<Poly>& F, long bound) {
  if (F.empty()) throw std::invalid_argument("helmer: random_combination of nothing");
  Poly s(F[0].ring());
  for (auto& f : F) s = s + f.scale_si(random_coeff(bound));
  return s;
}

Ideal intersect(const Ideal& I, const Ideal& J) {
  const RingPtr& R = I.ring();
  int t;
  RingPtr S = ring_plus_one(R, "helmer_s", t);
  auto m = identity_map(R->nvars());
  Poly T = Poly::var(S, t), one = Poly::constant(S, 1);
  std::vector<Poly> g;
  for (auto& p : I.gens()) g.push_back(T * p.embed(S, m));
  for (auto& p : J.gens()) g.push_back((one - T) * p.embed(S, m));
  Ideal E = eliminate(Ideal(S, g), {t});
  std::vector<Poly> vals;
  for (int i = 0; i < R->nvars(); ++i) vals.push_back(Poly::var(R, i));
  vals.push_back(Poly(R));
  std::vector<Poly> out;
  for (auto& p : E.gens()) out.push_back(p.substitute(R, vals));
  return Ideal(R, std::move(out));
}

Ideal saturate(const Ideal& I, const Ideal& J, const std::string& strategy) {
  const auto& G = J.gens();
  if (G.empty()) return Ideal(I.ring(), {Poly::constant(I.ring(), 1)});
  if (G.size() == 1) return saturate(I, G[0]);
  if (strategy == "exact") {
    std::optional<Ideal> acc;
    for (auto& g : G) {
      Ideal s = saturate(I, g);
      acc = acc ? intersect(*acc, s) : s;
    }
    return *acc;
  }
  return saturate(I, random_combination(G, 1000));
}

std::vector<std::vector<Poly>> jacobian(const std::vector<Poly>& F) {
  std::vector<std::vector<Poly>> M;
  for (auto& f : F) {
    std::vector<Poly> row;
    for (int v = 0; v < f.ring()->nvars(); ++v) row.push_back(f.derivative(v));
    M.push_back(std::move(row));
  }
  return M;
}

std::vector<Poly> minors(int k, const std::vector<std::vector<Poly>>& M) {
  std::vector<Poly> out;
  if (M.empty() || k <= 0) return out;
  const int m = static_cast<int>(M.size()), n = static_cast<int>(M[0].size());
  if (k > m || k > n) return out;
  const RingPtr& R = M[0][0].ring();
  // memoised Laplace expansion along the first row of the row subset
  std::map<std::pair<std::vector<int>, std::vector<int>>, Poly> memo;
  std::function<Poly(const std::vector<int>&, const std::vector<int>&)> det =
      [&](const std::vector<int>& rows, const std::vector<int>& cols) -> Poly {
    if (rows.size() == 1) return M[rows[0]][cols[0]];
    auto key = std::make_pair(rows, cols);
    auto it = memo.find(key);
    if (it != memo.end()) return it->second;
    std::vector<int> sub_rows(rows.begin() + 1, rows.end());
    Poly acc(R);
    for (size_t j = 0; j < cols.size(); ++j) {
      const Poly& a = M[rows[0]][cols[j]];
      if (a.is_zero()) continue;
      std::vector<int> sub_cols;
      for (size_t l = 0; l < cols.size(); ++l)
        if (l != j) sub_cols.push_back(cols[l]);
      Poly d = det(sub_rows, sub_cols);
      if (d.is_zero()) continue;
      Poly term = a * d;
      acc = (j % 2 == 0) ? acc + term : acc - term;
    }
    memo.emplace(key, acc);
    return acc;
  };
  std::vector<int> rsel(k), csel(k);
  std::function<void(int, int, std::vector<int>&, int, std::vector<std::vector<int>>&)> choose =
      [&](int start, int left, std::vector<int>& cur, int N, std::vector<std::vector<int>>& acc) {
        if (left == 0) { acc.push_back(cur); return; }
        for (int i = start; i <= N - left; ++i) {
          cur.push_back(i);
          choose(i + 1, left - 1, cur, N, acc);
          cur.pop_back();
        }
      };
  std::vector<std::vector<int>> RS, CS;
  std::vector<int> cur;
  choose(0, k, cur, m, RS);
  choose(0, k, cur, n, CS);
  for (auto& r : RS)
    for (auto& c : CS) {
      Poly d = det(r, c);
      if (!d.is_zero()) out.push_back(d);
    }
  return out;
}

Ideal jacobian_ideal(const Ideal& I) {
  int c = I.codim();
  if (c <= 0) return Ideal(I.ring(), {Poly::constant(I.ring(), 1)});  // 0-minors = (1)
  std::vector<Poly> g = I.gens();
  auto mins = minors(c, jacobian(I.gens()));
  g.insert(g.end(), mins.begin(), mins.end());
  return Ideal(I.ring(), std::move(g));
}

BlockData block_lc_lcm(const Ideal& I, const std::vector<int>& u) {
  const RingPtr& R = I.ring();
  const int n = R->nvars();
  std::vector<char> in_u(n, 0);
  for (int v : u) in_u[v] = 1;
  std::vector<int> perm;
  for (int v = 0; v < n; ++v)
    if (!in_u[v]) perm.push_back(v);
  const int ebl = static_cast<int>(perm.size());
  for (int v : u) perm.push_back(v);
  BlockData out{groebner(R, I.gens(), perm, ebl == n ? 0 : ebl), Poly::constant(R, 1)};
  Poly h = Poly::constant(R, 1);
  for (size_t gi = 0; gi < out.gb.polys.size(); ++gi) {
    const Poly& g = out.gb.polys[gi];
    const auto& L = out.gb.lead[gi];
    // terms of g sharing the lead's non-u exponents, with those exponents removed
    std::vector<std::vector<long>> exps;
    std::vector<fmpq*> cs;
    std::vector<fmpq> store(g.nterms());
    for (long t = 0; t < g.nterms(); ++t) {
      auto e = g.term_exp(t);
      bool same = true;
      for (int v = 0; v < n; ++v)
        if (!in_u[v] && e[v] != L[v]) { same = false; break; }
      if (!same) continue;
      for (int v = 0; v < n; ++v)
        if (!in_u[v]) e[v] = 0;
      fmpq_init(&store[t]);
      fmpq_mpoly_get_term_coeff_fmpq(&store[t], g.raw(), t, R->ctx());
      exps.push_back(e);
      cs.push_back(&store[t]);
    }
    Poly lc = Poly::from_terms(R, exps, cs);
    for (auto* c : cs) fmpq_clear(c);
    if (!lc.is_constant()) h = lcm(h, lc);
  }
  out.h = h.primitive();
  return out;
}

